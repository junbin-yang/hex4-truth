#include "hex4_core.h"

//=========================================================================
// 操作码名称
//=========================================================================
const char *hex4_opcode_name(uint8_t op) {
    static const char *tbl[] = {
        "ADD","SUB","MUL","NEG",
        "AND","OR","XOR","NOT","NAND","NOR",
        "CMP_EQ","CMP_GT","CMP_LT","CMP_RANGE",
        "FIT_THRESH","FIT_SCALE","FIT_CLAMP"
    };
    return (op <= HEX4_OP_MAX) ? tbl[op] : "ILLEGAL";
}

//=========================================================================
// 内部 LUT 查询
//=========================================================================
static inline void lut_dual_3b(const uint8_t raw[16], uint8_t a, uint8_t b,
                                hex4_result_t *r) {
    uint8_t v = raw[((a & 3) << 2) | (b & 3)];
    r->result  = (v >> 1) & 3;
    r->carry   = 0;
    r->tc_flag = v & 1;
    r->valid   = 1;
}

static inline void lut_dual_4b(const uint8_t raw[16], uint8_t a, uint8_t b,
                                hex4_result_t *r) {
    uint8_t v = raw[((a & 3) << 2) | (b & 3)];
    r->result  = (v >> 3) & 3;
    r->carry   = (v >> 2) & 1;
    r->tc_flag = (v >> 1) & 1;
    r->valid   = 1;
}

static inline void lut_unary_3b(const uint8_t raw[4], uint8_t a,
                                 hex4_result_t *r) {
    uint8_t v = raw[a & 3];
    r->result  = (v >> 1) & 3;
    r->carry   = 0;
    r->tc_flag = v & 1;
    r->valid   = 1;
}

//=========================================================================
// ADD — {result[1:0], carry, tc_flag}
//=========================================================================
hex4_result_t hex4_add(uint8_t a, uint8_t b) {
    static const uint8_t lut[16] = {
        (0<<3)|(0<<2)|(0<<1), (1<<3)|(0<<2)|(0<<1),
        (2<<3)|(0<<2)|(0<<1), (3<<3)|(0<<2)|(1<<1),
        (1<<3)|(0<<2)|(0<<1), (2<<3)|(0<<2)|(0<<1),
        (0<<3)|(1<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (2<<3)|(0<<2)|(0<<1), (0<<3)|(1<<2)|(1<<1),
        (1<<3)|(1<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (3<<3)|(0<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (3<<3)|(0<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
    };
    hex4_result_t r; lut_dual_4b(lut, a, b, &r); return r;
}

//=========================================================================
// SUB
//=========================================================================
hex4_result_t hex4_sub(uint8_t a, uint8_t b) {
    static const uint8_t lut[16] = {
        (0<<3)|(0<<2)|(0<<1), (2<<3)|(1<<2)|(1<<1),
        (1<<3)|(1<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (1<<3)|(0<<2)|(0<<1), (0<<3)|(0<<2)|(0<<1),
        (2<<3)|(1<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (2<<3)|(0<<2)|(0<<1), (1<<3)|(0<<2)|(0<<1),
        (0<<3)|(0<<2)|(0<<1), (3<<3)|(0<<2)|(1<<1),
        (3<<3)|(0<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
        (3<<3)|(0<<2)|(1<<1), (3<<3)|(0<<2)|(1<<1),
    };
    hex4_result_t r; lut_dual_4b(lut, a, b, &r); return r;
}

//=========================================================================
// MUL
//=========================================================================
hex4_result_t hex4_mul(uint8_t a, uint8_t b) {
    static const uint8_t lut[16] = {
        (0<<1)|0,(0<<1)|0,(0<<1)|0,(3<<1)|1,
        (0<<1)|0,(1<<1)|0,(2<<1)|0,(3<<1)|1,
        (0<<1)|0,(2<<1)|0,(1<<1)|1,(3<<1)|1,
        (3<<1)|1,(3<<1)|1,(3<<1)|1,(3<<1)|1,
    };
    hex4_result_t r; lut_dual_3b(lut, a, b, &r); return r;
}

//=========================================================================
// NEG
//=========================================================================
hex4_result_t hex4_neg(uint8_t a) {
    static const uint8_t lut[4] = {
        (0<<1)|0, (2<<1)|0, (1<<1)|0, (3<<1)|1,
    };
    hex4_result_t r; lut_unary_3b(lut, a, &r); return r;
}

//=========================================================================
// AND — 三态最小值
//=========================================================================
hex4_result_t hex4_and(uint8_t a, uint8_t b) {
    static const uint8_t lut[16] = {
        (0<<1)|0,(0<<1)|0,(0<<1)|0,(3<<1)|1,
        (0<<1)|0,(1<<1)|0,(1<<1)|0,(3<<1)|1,
        (0<<1)|0,(1<<1)|0,(2<<1)|0,(3<<1)|1,
        (3<<1)|1,(3<<1)|1,(3<<1)|1,(3<<1)|1,
    };
    hex4_result_t r; lut_dual_3b(lut, a, b, &r); return r;
}

//=========================================================================
