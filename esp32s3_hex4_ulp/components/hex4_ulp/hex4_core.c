//=========================================================================
// NOT — T0↔T2, T1↔T1
//=========================================================================
hex4_result_t hex4_not(uint8_t a) {
    static const uint8_t lut[4] = {
        (2<<1)|0, (1<<1)|0, (0<<1)|0, (3<<1)|1,
    };
    hex4_result_t r; lut_unary_3b(lut, a, &r); return r;
}

