//=========================================================================
// 统一调度
//=========================================================================
hex4_result_t hex4_exec(uint8_t opcode, uint8_t op_a, uint8_t op_b) {
    switch (opcode) {
        case HEX4_OP_ADD:       return hex4_add(op_a, op_b);
        case HEX4_OP_SUB:       return hex4_sub(op_a, op_b);
        case HEX4_OP_MUL:       return hex4_mul(op_a, op_b);
        case HEX4_OP_NEG:       return hex4_neg(op_a);
        case HEX4_OP_AND:       return hex4_and(op_a, op_b);
        case HEX4_OP_OR:        return hex4_or(op_a, op_b);
        case HEX4_OP_XOR:       return hex4_xor(op_a, op_b);
        case HEX4_OP_NOT:       return hex4_not(op_a);
        case HEX4_OP_NAND:      return hex4_nand(op_a, op_b);
        case HEX4_OP_NOR:       return hex4_nor(op_a, op_b);
        case HEX4_OP_CMP_EQ:    return hex4_cmp_eq(op_a, op_b);
        case HEX4_OP_CMP_GT:    return hex4_cmp_gt(op_a, op_b);
        case HEX4_OP_CMP_LT:    return hex4_cmp_lt(op_a, op_b);
        case HEX4_OP_CMP_RANGE: return hex4_cmp_range(op_a, op_b);
        case HEX4_OP_FIT_THRESH:return hex4_fit_thresh(op_a, op_b);
        case HEX4_OP_FIT_SCALE: return hex4_fit_scale(op_a, op_b);
        case HEX4_OP_FIT_CLAMP: return hex4_fit_clamp(op_a, op_b);
        default: { hex4_result_t r = {0,0,0,0}; return r; }
    }
}
